import type { MarketDataStatus } from '@/types/system';

/**
 * Data-source label that must accompany prices. Synthetic data is always flagged as SIMULATED DATA,
 * so generated prices are never mistaken for exchange prices.
 */
export function MarketDataBadge({ marketData }: { marketData?: MarketDataStatus }) {
  if (!marketData) return null;
  const simulated = marketData.mode === 'SIMULATION';
  return (
    <span
      title={simulated ? 'Prices are generated by the simulator. They are not NSE/BSE prices.' : undefined}
      className={`rounded-sm border px-2 py-0.5 text-[10px] font-bold tracking-wider ${
        simulated ? 'border-warn/40 bg-warn/10 text-warn' : 'border-accent/40 bg-accent/10 text-accent'
      }`}
    >
      {marketData.label}
    </span>
  );
}
