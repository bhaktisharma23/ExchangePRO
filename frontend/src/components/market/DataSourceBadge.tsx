import { useMarketStore } from '@/stores/marketStore';
import type { MarketDataSource } from '@/types/market';
import { formatTimeIst } from '@/utils/format';

const STREAM_TEXT = { connected: 'Live', connecting: 'Reconnecting…', disconnected: 'Offline' } as const;
const STREAM_DOT = { connected: 'bg-up', connecting: 'bg-warn', disconnected: 'bg-fg-muted' } as const;

/**
 * Data provenance shown next to prices: source label (e.g. SIMULATED DATA), last update time and live-stream
 * state. Required by the market-data policy: never present prices without their source.
 */
export function DataSourceBadge({ fallbackSource, fallbackAsOf }: {
  /** Used until the live store has data (e.g. the page was opened directly), so prices are never unlabelled. */
  fallbackSource?: MarketDataSource;
  fallbackAsOf?: string;
} = {}) {
  const source = useMarketStore((s) => s.source) ?? fallbackSource;
  const asOf = useMarketStore((s) => s.asOf) ?? fallbackAsOf ?? null;
  const stream = useMarketStore((s) => s.stream);
  return (
    <div className="flex flex-wrap items-center gap-3 text-[11px] text-fg-muted">
      {source && (
        <span
          title={source.realTime ? undefined : 'Generated by the EXCHANGE PRO simulator. Not NSE/BSE prices.'}
          className="rounded-sm border border-warn/40 bg-warn/10 px-1.5 py-0.5 font-bold tracking-wider text-warn"
        >
          {source.label}
        </span>
      )}
      <span>Updated {formatTimeIst(asOf)}</span>
      <span className="inline-flex items-center gap-1.5" role="status" aria-label={`Live stream ${STREAM_TEXT[stream]}`}>
        <span aria-hidden className={`h-1.5 w-1.5 rounded-full ${STREAM_DOT[stream]}`} />
        {STREAM_TEXT[stream]}
      </span>
    </div>
  );
}
