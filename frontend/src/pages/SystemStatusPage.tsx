import { RefreshCw, ServerCrash } from 'lucide-react';
import { Panel } from '@/components/ui/Panel';
import { KeyValueList } from '@/components/ui/KeyValueList';
import { StatusIndicator } from '@/components/ui/StatusIndicator';
import { useSystemStatus } from '@/hooks/useSystemStatus';
import { ApiError } from '@/services/apiClient';
import { formatDateTimeIst, orDash } from '@/utils/format';

/** Live view of backend, database and market-data configuration (Phase 1 health screen). */
export function SystemStatusPage() {
  const { data, error, isPending, isFetching, refetch } = useSystemStatus();

  const refreshButton = (
    <button
      type="button"
      onClick={() => void refetch()}
      disabled={isFetching}
      className="inline-flex items-center gap-1 rounded-sm px-2 py-1 text-[11px] text-fg-muted hover:bg-surface-3 hover:text-fg disabled:opacity-50"
    >
      <RefreshCw className={`h-3 w-3 ${isFetching ? 'animate-spin' : ''}`} aria-hidden />
      Refresh
    </button>
  );

  return (
    <div className="mx-auto max-w-5xl space-y-4">
      <div className="flex items-end justify-between">
        <div>
          <h1 className="text-base font-semibold">System status</h1>
          <p className="text-fg-muted">Live health of the EXCHANGE PRO platform components.</p>
        </div>
        {refreshButton}
      </div>

      {isPending && <LoadingState />}
      {error && !data && <ErrorState error={error} />}

      {data && (
        <div className="grid gap-4 md:grid-cols-2">
          <Panel title="Backend API">
            <KeyValueList
              items={[
                { label: 'State', value: <StatusIndicator state={error ? 'DOWN' : 'UP'} /> },
                { label: 'Application', value: data.application },
                { label: 'Version', value: data.version },
                { label: 'Profiles', value: data.activeProfiles.length ? data.activeProfiles.join(', ') : 'default' },
                { label: 'Server time', value: formatDateTimeIst(data.serverTime) },
              ]}
            />
          </Panel>

          <Panel title="Database">
            <KeyValueList
              items={[
                { label: 'State', value: <StatusIndicator state={data.database.state} /> },
                { label: 'Engine', value: orDash(data.database.productVersion) },
                { label: 'Schema version', value: orDash(data.database.schemaVersion) },
              ]}
            />
          </Panel>

          <Panel title="Market data" className="md:col-span-2">
            <KeyValueList
              items={[
                { label: 'Mode', value: data.marketData.mode },
                { label: 'Label', value: data.marketData.label },
                { label: 'Real-time exchange prices', value: data.marketData.realTime ? 'Yes' : 'No' },
              ]}
            />
            {data.marketData.mode === 'SIMULATION' && (
              <p className="mt-3 border-t border-line pt-3 text-fg-muted">
                Prices on this platform are generated by the simulator and are not NSE/BSE prices.
              </p>
            )}
          </Panel>
        </div>
      )}
    </div>
  );
}

function LoadingState() {
  return (
    <div role="status" aria-live="polite" className="grid gap-4 md:grid-cols-2">
      <span className="sr-only">Loading system status</span>
      {[0, 1].map((i) => (
        <div key={i} className="h-40 animate-pulse rounded-sm border border-line bg-surface" />
      ))}
    </div>
  );
}

function ErrorState({ error }: { error: Error }) {
  const apiError = error instanceof ApiError ? error : undefined;
  return (
    <div role="alert" className="flex items-start gap-3 rounded-sm border border-down/40 bg-down/10 p-4">
      <ServerCrash className="mt-0.5 h-5 w-5 shrink-0 text-down" aria-hidden />
      <div>
        <p className="font-semibold text-down">
          {apiError?.isNetworkError ? 'Backend unreachable' : 'Status request failed'}
        </p>
        <p className="text-fg-muted">{error.message}</p>
        {apiError?.isNetworkError && (
          <p className="mt-1 text-fg-muted">Start the backend (see README) and press Refresh.</p>
        )}
        {apiError?.correlationId && (
          <p className="mt-1 font-mono text-[11px] text-fg-muted">Correlation ID: {apiError.correlationId}</p>
        )}
      </div>
    </div>
  );
}
